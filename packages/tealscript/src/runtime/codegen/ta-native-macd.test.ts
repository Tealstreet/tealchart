describe('Native MACD EMA children', () => {
  it('restores all child seed and recurrence state on replacement and rollback', () => {
    const macd = new MACD(12, 26, 9);
    closes.slice(0, 40).forEach((source) => macd.compute(source));
    expect(macd.compute(NaN).every(Number.isNaN)).toBe(true);
    expect(macd.recompute(closes[40])).toEqual(fixtures[0].expected.map((column) => column[40]));
    expect(macd.recompute(NaN).every(Number.isNaN)).toBe(true);
    expect(macd.compute(NaN).every(Number.isNaN)).toBe(true);
    expect(macd.compute(closes[42])).toEqual(fixtures[1].expected.map((column) => column[42]));
    const snapshot = macd.save();
    expect(macd.compute(closes[43])).toEqual(fixtures[1].expected.map((column) => column[43]));
    macd.restore(snapshot);
    expect(macd.compute(closes[43])).toEqual(fixtures[1].expected.map((column) => column[43]));
  });
  it.each(fixtures)('$kind seeds and publishes every child from native valid-call history', ({ source, expected }) => {
    const result = executeScript(
      parse(`//@version=6
indicator("Native MACD startup")
s = ${source}
[m, sLine, h] = ta.macd(s, 12, 26, 9)
plot(m, "line")
plot(sLine, "signal")
plot(h, "hist")`),
      bars,
    );
    expect(result.errors).toEqual([]);
    expect(result.plots).toHaveLength(3);
    expected.forEach((values, column) => {
      expect(result.plots[column].values).toHaveLength(values.length);
      values.forEach((value, index) =>
        expect(result.plots[column].values[index], `column ${column}, bar ${index}`).toBe(value),
      );
    });
  });
});
